    /// A project and the user state root that holds decisions about it.
    struct Workspace {
        project: TempDir,
        home: TempDir,
    }

    impl Workspace {
        fn new() -> Self {
            Self {
                project: tempfile::tempdir().expect("a project"),
                home: tempfile::tempdir().expect("a home"),
            }
        }

        fn user_root(&self) -> PathBuf {
            self.home.path().join(".smith")
        }

        fn store(&self) -> TrustStore {
            TrustStore::open(self.user_root()).expect("a trust store")
        }

        fn write_project_skill(&self, name: &str, body: &str) -> PathBuf {
            write_skill(&self.project.path().join(".smith"), name, body)
        }

        fn resolve(
            &self,
            trust: &TrustStore,
        ) -> (crate::skills::ResolvedSmithSkills, Vec<SkillProblem>) {
            let (sources, problems, _) = discover_into(
                SmithSkillSources::new(),
                &self.user_root(),
                self.project.path(),
                trust,
            );
            (sources.resolve().expect("the catalog resolves"), problems)
        }
    }

    #[test]
    fn agents_locations_contribute_to_their_own_layers() {
        let workspace = Workspace::new();
        let user_path = write_skill(&workspace.home.path().join(".agents"), "review", REVIEW);
        let project_path = write_skill(&workspace.project.path().join(".agents"), "deploy", REVIEW);
        let mut trust = workspace.store();
        let (sources, problems, paths) = discover_into(
            SmithSkillSources::new(),
            &workspace.user_root(),
            workspace.project.path(),
            &trust,
        );
        assert!(problems.is_empty(), "{problems:?}");
        assert_eq!(paths, [("deploy".to_owned(), project_path.clone())]);
        let resolved = sources.resolve().expect("the shared skills resolve");
        assert!(resolved.index().iter().any(|entry| {
            entry.name() == "review" && entry.layer == SmithSkillLayer::User && entry.activatable
        }));
        assert!(resolved.index().iter().any(|entry| {
            entry.name() == "deploy"
                && entry.layer == SmithSkillLayer::Workspace
                && !entry.activatable
        }));
        assert_eq!(resolved.abilities().len(), 1);
        fs::write(
            &user_path,
            "---\ndescription: Review\n---\n\nChanged user content.\n",
        )
        .expect("a later user edit");
        assert!(resolved.abilities()[0].materialize().is_err());

        let executable = Executable::from_file(
            workspace.project.path(),
            ExecutableKind::Skill,
            &project_path,
        )
        .expect("the shared skill is project content");
        for (decision, activatable) in [(TrustDecision::Deny, false), (TrustDecision::Allow, true)]
        {
            trust
                .record(workspace.project.path(), &executable, decision)
                .expect("the decision records");
            let (resolved, problems) = workspace.resolve(&trust);
            assert!(problems.is_empty(), "{problems:?}");
            assert_eq!(
                resolved
                    .index()
                    .iter()
                    .find(|entry| entry.name() == "deploy")
                    .expect("the shared workspace declaration")
                    .activatable,
                activatable
            );
            if activatable {
                let ability = resolved
                    .abilities()
                    .iter()
                    .find(|ability| ability.name() == "deploy")
                    .expect("the trusted skill activates");
                assert_eq!(
                    ability.materialize().expect("the reviewed body"),
                    Activated::SkillInstructions(REVIEW.into())
                );
                fs::write(
                    &project_path,
                    "---\ndescription: Changed\n---\n\nChanged.\n",
                )
                .expect("a later project edit");
                assert!(ability.materialize().is_err());
            }
        }
        let (resolved, _) = workspace.resolve(&trust);
        assert!(
            !resolved
                .index()
                .iter()
                .any(|entry| { entry.name() == "deploy" && entry.activatable })
        );
    }

    #[test]
    fn smith_wins_same_name_in_each_layer_and_reports_both_paths() {
        let workspace = Workspace::new();
        let mut expected = Vec::new();
        let smith_body = "---\ndescription: Smith copy\n---\n\nSMITH BODY\n";
        for (root, name) in [
            (workspace.home.path(), "review"),
            (workspace.project.path(), "deploy"),
        ] {
            let smith = write_skill(&root.join(".smith"), name, smith_body);
            let agents = write_skill(&root.join(".agents"), name, REVIEW);
            expected.push((name, smith, agents));
        }
        let mut trust = workspace.store();
        // Trusting the losing copy must not bypass the winner's own decision.
        let executable = Executable::from_file(
            workspace.project.path(),
            ExecutableKind::Skill,
            &expected[1].2,
        )
        .expect("the shared skill is project content");
        trust
            .record(workspace.project.path(), &executable, TrustDecision::Allow)
            .expect("trust the losing copy");
        let (sources, problems, paths) = discover_into(
            SmithSkillSources::new(),
            &workspace.user_root(),
            workspace.project.path(),
            &trust,
        );
        assert_eq!(problems.len(), 2);
        for (name, smith, agents) in &expected {
            let problem = problems
                .iter()
                .find(|problem| problem.name == *name)
                .expect("the losing copy is named");
            assert_eq!(&problem.path, agents);
            assert!(problem.reason.contains("shadowed"));
            assert!(problem.reason.contains(smith.to_str().unwrap()));
            assert!(problem.reason.contains(agents.to_str().unwrap()));
        }
        assert_eq!(paths, [("deploy".to_owned(), expected[1].1.clone())]);
        let resolved = sources.resolve().expect("no duplicate declarations");
        assert_eq!(resolved.index().len(), 2);
        assert!(
            resolved
                .index()
                .iter()
                .all(|entry| entry.description() == "Smith copy")
        );
        assert!(
            !resolved
                .index()
                .iter()
                .find(|entry| entry.name() == "deploy")
                .unwrap()
                .activatable
        );
        assert_eq!(
            resolved.abilities()[0]
                .materialize()
                .expect("the user winner"),
            Activated::SkillInstructions(smith_body.into())
        );
    }

